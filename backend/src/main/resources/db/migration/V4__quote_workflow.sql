-- V1-V3 remain unchanged. Quote ownership and visibility are enforced by services.
ALTER TABLE workshops ADD COLUMN contact_email VARCHAR(254);
ALTER TABLE workshops ADD COLUMN phone VARCHAR(30);
CREATE TABLE tags (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(120) NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL
);
CREATE TABLE product_tags (
 product_id BIGINT NOT NULL REFERENCES products(id),
 tag_id BIGINT NOT NULL REFERENCES tags(id), PRIMARY KEY(product_id,tag_id)
);
CREATE INDEX product_tags_tag_idx ON product_tags(tag_id);
CREATE TABLE quote_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 buyer_account_id BIGINT NOT NULL REFERENCES accounts(id),
 category_id BIGINT REFERENCES categories(id),
 title VARCHAR(160), quantity INTEGER CHECK(quantity>0), unit VARCHAR(40),
 spec VARCHAR(4000), note VARCHAR(2000), desired_by DATE,
 bidding_deadline TIMESTAMPTZ,
 mode VARCHAR(16) NOT NULL CHECK(mode IN ('OPEN','TARGETED')),
 target_workshop_id BIGINT REFERENCES workshops(id),
 buyer_contact_name VARCHAR(160), buyer_contact_email VARCHAR(254), buyer_contact_phone VARCHAR(30),
 status VARCHAR(24) NOT NULL CHECK(status IN ('DRAFT','SENT','BIDDING','ACCEPTED','IN_PRODUCTION','DELIVERED','CANCELLED')),
 accepted_quote_id BIGINT,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CHECK(mode='TARGETED' OR target_workshop_id IS NULL),
 CHECK((status IN ('ACCEPTED','IN_PRODUCTION','DELIVERED')) = (accepted_quote_id IS NOT NULL))
);
CREATE INDEX quote_requests_buyer_idx ON quote_requests(buyer_account_id,id);
CREATE INDEX quote_requests_status_idx ON quote_requests(status);
CREATE INDEX quote_requests_target_idx ON quote_requests(target_workshop_id);
CREATE TABLE quote_request_tags (
 request_id BIGINT NOT NULL REFERENCES quote_requests(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES tags(id), PRIMARY KEY(request_id,tag_id)
);
CREATE INDEX quote_request_tags_tag_idx ON quote_request_tags(tag_id);
CREATE TABLE quotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL REFERENCES quote_requests(id) ON DELETE CASCADE,
 workshop_id BIGINT NOT NULL REFERENCES workshops(id),
 unit_price NUMERIC(15,2) NOT NULL CHECK(unit_price>0),
 total_price NUMERIC(15,2) NOT NULL CHECK(total_price>0),
 lead_time_days INTEGER NOT NULL CHECK(lead_time_days BETWEEN 1 AND 3650),
 note VARCHAR(2000),
 status VARCHAR(24) NOT NULL CHECK(status IN ('SUBMITTED','WITHDRAWN','ACCEPTED','NOT_SELECTED')),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(request_id,workshop_id), UNIQUE(request_id,id)
);
CREATE UNIQUE INDEX quotes_one_accepted_per_request ON quotes(request_id) WHERE status='ACCEPTED';
CREATE INDEX quotes_workshop_idx ON quotes(workshop_id,request_id);
ALTER TABLE quote_requests ADD CONSTRAINT accepted_quote_belongs_to_request
 FOREIGN KEY(id,accepted_quote_id) REFERENCES quotes(request_id,id);
CREATE TABLE quote_request_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL REFERENCES quote_requests(id) ON DELETE CASCADE,
 actor_account_id BIGINT NOT NULL REFERENCES accounts(id),
 from_status VARCHAR(24), to_status VARCHAR(24) NOT NULL,
 note VARCHAR(500) NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX quote_events_request_idx ON quote_request_events(request_id,id);
